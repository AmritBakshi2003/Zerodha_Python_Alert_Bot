#!/usr/bin/env python3
"""Refresh ``config/holidays.yaml`` from the official NSE holiday page (F3).

The bot ships with an empty list and never invents dates. Run this after NSE
publishes the next year's calendar, then review the diff before committing:

    python scripts/refresh_holidays.py --year 2026
    python scripts/refresh_holidays.py --year 2026 --dry-run
    python scripts/refresh_holidays.py --html saved-page.html --year 2026

The parser is deliberately small and fixture-tested: NSE changes its markup, so
``--dry-run`` prints exactly what would be written and a parse that finds
nothing is an error, never a silently empty list.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
import urllib.request
from collections.abc import Iterable, Sequence
from pathlib import Path

DEFAULT_URL = "https://www.nseindia.com/resources/exchange-communication-holidays"
DEFAULT_OUT = Path("config/holidays.yaml")

_ROW = re.compile(r"<tr[^>]*>(.*?)</tr>", re.IGNORECASE | re.DOTALL)
_CELL = re.compile(r"<t[dh][^>]*>(.*?)</t[dh]>", re.IGNORECASE | re.DOTALL)
_TAG = re.compile(r"<[^>]+>")
_DATE = re.compile(r"(\d{1,2})-([A-Za-z]{3})-(\d{4})")
_MONTHS = {
    "jan": 1,
    "feb": 2,
    "mar": 3,
    "apr": 4,
    "may": 5,
    "jun": 6,
    "jul": 7,
    "aug": 8,
    "sep": 9,
    "oct": 10,
    "nov": 11,
    "dec": 12,
}


def _text(fragment: str) -> str:
    return " ".join(_TAG.sub(" ", fragment).split())


def parse_holidays_html(html: str, *, year: int) -> list[tuple[dt.date, str]]:
    """Parse the NSE holiday table, keeping only rows from ``year``.

    Raises ``ValueError`` when nothing matched: an empty result almost always
    means the page markup changed, and silently writing ``[]`` would turn a
    holiday into a "stalled feed" (the exact F3 failure).
    """
    found: dict[dt.date, str] = {}
    for row in _ROW.findall(html):
        cells = [_text(cell) for cell in _CELL.findall(row)]
        if len(cells) < 2:
            continue
        match = _DATE.search(" ".join(cells))
        if match is None:
            continue
        day_number, month_name, row_year = match.groups()
        month = _MONTHS.get(month_name.lower())
        if month is None or int(row_year) != year:
            continue
        try:
            day = dt.date(year, month, int(day_number))
        except ValueError:
            continue
        description = cells[-1] if cells[-1] != match.group(0) else ""
        found[day] = description or "NSE holiday"

    if not found:
        raise ValueError(
            f"no holidays for {year} found in the page; the markup may have changed — "
            "save the page and inspect it before trusting an empty list"
        )
    return sorted(found.items())


def write_holidays(path: Path, entries: Iterable[tuple[dt.date, str]], *, year: int) -> None:
    """Write the mapping shape that ``load_holidays`` reads back."""
    rows = sorted(entries)
    lines = [
        "# NSE trading holidays.",
        "#",
        f"# Generated by scripts/refresh_holidays.py for {year}.",
        "# Review the diff against the official NSE circular before committing.",
        "",
        "holidays:",
    ]
    for day, description in rows:
        safe = description.replace(":", " -").replace("#", "").strip()
        lines.append(f"  {day.isoformat()}: {safe}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def fetch(url: str, timeout: float = 20.0) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": "kite-alerts/refresh-holidays"})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return response.read().decode("utf-8", errors="replace")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Refresh NSE holidays from the official page.")
    parser.add_argument("--year", type=int, default=dt.date.today().year)
    parser.add_argument("--url", default=DEFAULT_URL)
    parser.add_argument("--html", type=Path, help="parse a saved page instead of fetching")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    try:
        html = args.html.read_text(encoding="utf-8") if args.html else fetch(args.url)
        rows = parse_holidays_html(html, year=args.year)
    except (OSError, ValueError, urllib.error.URLError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    for day, description in rows:
        print(f"{day.isoformat()}  {description}")
    if args.dry_run:
        print(f"{len(rows)} holidays for {args.year} (dry run, nothing written)")
        return 0

    write_holidays(args.out, rows, year=args.year)
    print(f"wrote {len(rows)} holidays for {args.year} to {args.out}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
